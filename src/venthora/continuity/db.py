"""One way to reach a database: a SQLite file or PostgreSQL, chosen by URL.

    connect("data/venthora_continuity.db")                 SQLite (also "sqlite:///path")
    connect("postgresql://user:pass@host:5432/venthora")   PostgreSQL, through psycopg

Code written against this module uses SQLite's SQL: `?` placeholders, INSERT OR IGNORE, INSERT OR REPLACE. For
PostgreSQL each statement is translated by `to_postgres`, which is a pure function and tested on its own. What it
translates is exactly what VENTHORA's stores use; anything else is passed through unchanged.
"""
from __future__ import annotations

import re
import sqlite3

_OR_IGNORE = re.compile(r"^\s*INSERT\s+OR\s+IGNORE\s+INTO\s+", re.I)
_OR_REPLACE = re.compile(r"^\s*INSERT\s+OR\s+REPLACE\s+INTO\s+(\w+)\s*(\(([^)]*)\))?", re.I)
_TYPES = ((re.compile(r"\bINTEGER\s+PRIMARY\s+KEY\s+AUTOINCREMENT\b", re.I), "BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY"),
          (re.compile(r"\bBLOB\b", re.I), "BYTEA"))


def is_postgres(url: str) -> bool:
    return url.startswith(("postgresql://", "postgres://"))


def _placeholders(sql: str) -> str:
    """`?` -> `%s`, leaving a question mark inside a quoted string alone; a literal % is doubled for the driver."""
    out, quote = [], None
    for ch in sql:
        if quote:
            out.append("%%" if ch == "%" else ch)
            if ch == quote:
                quote = None
        elif ch in ("'", '"'):
            quote = ch
            out.append(ch)
        else:
            out.append("%s" if ch == "?" else "%%" if ch == "%" else ch)
    return "".join(out)


def to_postgres(sql: str, keys: dict[str, list[str]] | None = None) -> str:
    """A statement in SQLite's dialect, as PostgreSQL takes it. `keys`: table -> its primary key columns, needed to
    turn INSERT OR REPLACE into an upsert (PostgreSQL must be told which conflict to resolve)."""
    for pattern, replacement in _TYPES:
        sql = pattern.sub(replacement, sql)
    if _OR_IGNORE.match(sql):
        return _placeholders(_OR_IGNORE.sub("INSERT INTO ", sql, count=1).rstrip().rstrip(";")) + " ON CONFLICT DO NOTHING"
    m = _OR_REPLACE.match(sql)
    if m:
        table, cols = m.group(1), [c.strip() for c in (m.group(3) or "").split(",") if c.strip()]
        pk = (keys or {}).get(table)
        if not pk or not cols:
            raise ValueError(f"INSERT OR REPLACE INTO {table}: name the columns and give the table's primary key to translate it")
        rest = [c for c in cols if c not in pk]
        action = "DO UPDATE SET " + ", ".join(f"{c} = EXCLUDED.{c}" for c in rest) if rest else "DO NOTHING"
        body = re.sub(r"^\s*INSERT\s+OR\s+REPLACE\s+INTO\s+", "INSERT INTO ", sql, count=1, flags=re.I).rstrip().rstrip(";")
        return _placeholders(body) + f" ON CONFLICT ({', '.join(pk)}) {action}"
    return _placeholders(sql)


class Connection:
    """The few things the continuity code needs from either database, with one behaviour: `execute` returns rows as
    dictionaries, a `with` block is one transaction (committed at the end, rolled back on an error)."""

    def __init__(self, raw, *, postgres: bool, keys: dict[str, list[str]] | None = None):
        self.raw, self.postgres, self.keys = raw, postgres, keys or {}

    def execute(self, sql: str, params: tuple = ()) -> list[dict]:
        cur = self.raw.cursor()
        cur.execute(to_postgres(sql, self.keys) if self.postgres else sql, params)
        if cur.description is None:
            return []
        names = [d[0] for d in cur.description]
        return [dict(zip(names, row, strict=True)) for row in cur.fetchall()]

    def executemany(self, sql: str, rows: list[tuple]) -> None:
        if rows:
            self.raw.cursor().executemany(to_postgres(sql, self.keys) if self.postgres else sql, rows)

    def __enter__(self) -> Connection:
        return self

    def __exit__(self, exc_type, exc, tb) -> None:
        if exc_type is None:
            self.raw.commit()
        else:
            self.raw.rollback()

    def close(self) -> None:
        self.raw.close()


def connect(url: str, keys: dict[str, list[str]] | None = None) -> Connection:
    if is_postgres(url):
        try:
            import psycopg  # the PostgreSQL driver; only needed when a PostgreSQL URL is configured
        except ImportError as exc:
            raise RuntimeError("a PostgreSQL URL is configured but the driver is not installed: pip install 'psycopg[binary]'") from exc
        return Connection(psycopg.connect(url), postgres=True, keys=keys)
    path = url[len("sqlite:///"):] if url.startswith("sqlite:///") else url
    return Connection(sqlite3.connect(path, timeout=15), postgres=False, keys=keys)
