"""Continuity: one server pays, a standby that takes over knows what the bank already paid, and nothing pays by itself
while safe mode is on. Tested without a bank, a mailbox or a second server: each part takes what it needs."""
import asyncio
import sqlite3
from contextlib import closing

import pytest

from venthora.continuity import db, guard, replicate, takeover
from venthora.continuity.lease import WriterLease
from venthora.execution.store import ExecutionStore


class Clock:
    def __init__(self, t=1_000.0):
        self.t = t

    def __call__(self):
        return self.t


class Org:
    def __init__(self):
        self.rows = {}

    def get(self, kind, rid):
        return self.rows.get((kind, rid))

    def _put(self, kind, rec, by):
        self.rows[(kind, rec["_id"])] = rec


# -- the SQL differences, translated -----------------------------------------------------------------------------

def test_sqlite_sql_becomes_postgresql():
    assert db.to_postgres("SELECT * FROM t WHERE a = ? AND b = ?") == "SELECT * FROM t WHERE a = %s AND b = %s"
    assert db.to_postgres("SELECT '?' AS q, x FROM t WHERE y LIKE '50%' AND z = ?") == "SELECT '?' AS q, x FROM t WHERE y LIKE '50%%' AND z = %s"
    assert db.to_postgres("INSERT OR IGNORE INTO t (a, b) VALUES (?, ?)") == "INSERT INTO t (a, b) VALUES (%s, %s) ON CONFLICT DO NOTHING"
    assert (db.to_postgres("INSERT OR REPLACE INTO payouts (payout_key, status, transfer_id) VALUES (?, ?, ?)", {"payouts": ["payout_key"]})
            == "INSERT INTO payouts (payout_key, status, transfer_id) VALUES (%s, %s, %s) ON CONFLICT (payout_key) DO UPDATE SET status = EXCLUDED.status, transfer_id = EXCLUDED.transfer_id")
    assert "BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY" in db.to_postgres("CREATE TABLE e (seq INTEGER PRIMARY KEY AUTOINCREMENT, body BLOB)")
    assert "BYTEA" in db.to_postgres("CREATE TABLE e (seq INTEGER PRIMARY KEY AUTOINCREMENT, body BLOB)")
    with pytest.raises(ValueError):  # PostgreSQL must be told which conflict to resolve: never guessed
        db.to_postgres("INSERT OR REPLACE INTO payouts VALUES (?, ?, ?)")
    assert db.is_postgres("postgresql://u:p@h/db") and not db.is_postgres("data/x.db")


def test_a_postgresql_url_without_the_driver_says_what_to_install(monkeypatch):
    import builtins

    real = builtins.__import__

    def no_driver(name, *a, **kw):
        if name == "psycopg":
            raise ImportError(name)
        return real(name, *a, **kw)

    monkeypatch.setattr(builtins, "__import__", no_driver)
    with pytest.raises(RuntimeError, match="psycopg"):
        db.connect("postgresql://u:p@h/db")


# -- the writer lease --------------------------------------------------------------------------------------------

def test_only_one_server_holds_the_lease(tmp_path):
    url, clock = str(tmp_path / "lease.db"), Clock()
    one, two = WriterLease(url, "app-1", clock=clock), WriterLease(url, "app-2", clock=clock)
    assert one.acquire() and one.holds()
    assert not two.acquire() and not two.holds()  # the primary is alive: the standby gets nothing
    assert two.holder()["holder"] == "app-1" and two.holder()["live"] is True
    assert one.acquire()  # taking what is already ours is not an error


def test_a_dead_primarys_lease_runs_out_and_the_standby_takes_it(tmp_path):
    url, clock = str(tmp_path / "lease.db"), Clock()
    one, two = WriterLease(url, "app-1", ttl_s=180, clock=clock), WriterLease(url, "app-2", ttl_s=180, clock=clock)
    one.acquire()
    clock.t += 179
    assert one.renew() and not two.acquire()  # renewed in time
    clock.t += 181  # app-1 died: no renewal
    assert not one.holds()
    assert two.acquire() and two.holds()
    # app-1 was only cut off and comes back: it does not get the lease back, and it knows it must not pay
    assert not one.renew() and not one.acquire() and not one.holds()


def test_a_planned_switch_releases_the_lease_at_once(tmp_path):
    url, clock = str(tmp_path / "lease.db"), Clock()
    one, two = WriterLease(url, "app-1", clock=clock), WriterLease(url, "app-2", clock=clock)
    one.acquire()
    one.release()
    assert two.acquire() and not one.holds()
    two.release()  # releasing someone else's lease changes nothing
    one.release()
    assert one.acquire()


# -- may this server pay? ------------------------------------------------------------------------------------------

def test_a_single_server_always_pays_and_a_cut_off_one_never_does(tmp_path, monkeypatch):
    monkeypatch.delenv("VENTHORA_CONTINUITY_URL", raising=False)
    monkeypatch.setattr(guard, "_lease", None)
    assert guard.may_pay() == (True, "single server: no other writer exists")
    url = str(tmp_path / "lease.db")
    WriterLease(url, "app-2").acquire()  # another server is the writer
    monkeypatch.setenv("VENTHORA_CONTINUITY_URL", url)
    monkeypatch.setenv("VENTHORA_NODE", "app-1")
    ok, why = guard.may_pay()
    assert ok is False and "app-2 holds the lease" in why
    monkeypatch.setenv("VENTHORA_CONTINUITY_URL", str(tmp_path / "no" / "such" / "dir" / "lease.db"))
    monkeypatch.setattr(guard, "_lease", None)
    ok, why = guard.may_pay()
    assert ok is False and "cannot be read" in why  # a lease that cannot be read is a lease not held


def test_paying_never_takes_another_servers_lease_not_even_an_expired_one(tmp_path, monkeypatch):
    url, clock = str(tmp_path / "lease.db"), Clock()
    primary, standby = WriterLease(url, "app-1", clock=clock), WriterLease(url, "app-2", clock=clock)
    assert primary.keep() and not standby.keep()  # the first server takes a lease that was never taken; the second does not
    clock.t += 10_000  # the primary was idle (or dead) long past its lease
    assert not standby.keep() and standby.holder()["holder"] == "app-1"  # paying is not a takeover
    assert primary.keep()  # nobody took it: the primary carries on
    clock.t += 10_000
    assert standby.acquire()  # the takeover, started by a person
    assert not primary.keep() and standby.keep()  # the primary that comes back no longer pays
    monkeypatch.setenv("VENTHORA_CONTINUITY_URL", url)
    monkeypatch.setenv("VENTHORA_NODE", "app-3")
    monkeypatch.setattr(guard, "_lease", None)
    before = WriterLease(url, "x").holder()

    class Org:
        def get(self, kind, rid):
            return None

    s = guard.status(Org())
    assert s["may_pay"] is False and "app-2 holds the lease" in s["why"] and WriterLease(url, "x").holder() == before  # reading the status changes nothing


def test_safe_mode_stops_automatic_payments_only(monkeypatch):
    monkeypatch.delenv("VENTHORA_CONTINUITY_URL", raising=False)
    monkeypatch.setattr(guard, "_lease", None)
    org = Org()
    assert guard.may_pay_automatically(org)[0] is True
    with pytest.raises(ValueError):
        guard.set_safe_mode(org, True, "  ", "Fitri Hakim")  # a reason is required
    guard.set_safe_mode(org, True, "a payment went to the wrong account", "Fitri Hakim")
    ok, why = guard.may_pay_automatically(org)
    assert ok is False and "wrong account" in why
    assert guard.may_pay()[0] is True  # a person can still approve and pay one request deliberately
    guard.set_safe_mode(org, False, "", "Fitri Hakim")
    assert guard.may_pay_automatically(org)[0] is True and guard.status(org)["safe_mode"]["on"] is False


# -- replication ---------------------------------------------------------------------------------------------------

def _stores(tmp_path):
    data = tmp_path / "data"
    (data / "saas" / "acme").mkdir(parents=True)
    for path, rows in ((data / "venthora_execution.db", 4), (data / "saas" / "acme" / "org.db", 2)):
        with closing(sqlite3.connect(path)) as c:
            c.execute("CREATE TABLE records (id TEXT PRIMARY KEY, amount INTEGER, body BLOB)")
            c.executemany("INSERT INTO records VALUES (?, ?, ?)", [(f"r{i}", i * 100, b"\x00\x01") for i in range(rows)])
            c.commit()
    return data


def test_every_store_is_copied_whole_and_the_counts_are_checked(tmp_path):
    data, target = _stores(tmp_path), str(tmp_path / "replica.db")
    out = replicate.run(data, target, now=5_000.0)
    assert [(r["store"], r["rows"], r["ok"]) for r in out] == [("saas_acme_org", 2, True), ("venthora_execution", 4, True)]
    with closing(sqlite3.connect(target)) as c:  # two stores with a table of the same name never collide
        assert c.execute('SELECT COUNT(*) FROM "venthora_execution__records"').fetchone()[0] == 4
        assert c.execute('SELECT COUNT(*) FROM "saas_acme_org__records"').fetchone()[0] == 2
        assert c.execute('SELECT amount, body FROM "venthora_execution__records" WHERE id = ?', ("r3",)).fetchone() == (300, b"\x00\x01")
    assert replicate.last_run(target) == {"run_at": 5_000.0, "stores": 2, "ok": True, "rows": 6}
    # the store changes; the next copy replaces the old one, it does not add to it
    with closing(sqlite3.connect(data / "venthora_execution.db")) as c:
        c.execute("DELETE FROM records WHERE id = 'r0'")
        c.commit()
    replicate.run(data, target, now=6_000.0)
    with closing(sqlite3.connect(target)) as c:
        assert c.execute('SELECT COUNT(*) FROM "venthora_execution__records"').fetchone()[0] == 3
    assert replicate.last_run(target)["run_at"] == 6_000.0


def test_one_store_that_cannot_be_read_is_reported_and_the_others_still_copy(tmp_path):
    data, target = _stores(tmp_path), str(tmp_path / "replica.db")
    (data / "broken.db").write_bytes(b"this is not a database")
    out = {r["store"]: r for r in replicate.run(data, target)}
    assert out["broken"]["ok"] is False and out["venthora_execution"]["ok"] is True and out["saas_acme_org"]["ok"] is True
    assert replicate.last_run(target)["ok"] is False  # a takeover is told the copy was not complete


# -- taking over ---------------------------------------------------------------------------------------------------

class Bank:
    def __init__(self, transfers):
        self.transfers = transfers

    async def list_transfers(self, pages=2, page_size=100):
        return self.transfers


TRANSFERS = [
    {"id": "tr-1", "status": "PAID", "reference": "REQ-SLS-88412 straits-line-88412"},
    {"id": "tr-2", "status": "PROCESSING", "reference": "REQ-PHI-2611 pacific-health-2611"},  # in flight when the primary died
    {"id": "tr-3", "status": "FAILED", "reference": "REQ-CD-2611 clouddesk-2611"},  # never left: may be paid again
    {"id": "tr-4", "status": "PAID", "reference": "DOA-PAYROLL-2026-11-001"},  # no invoice: locked by its obligation id
    {"id": "tr-5", "status": "PAID", "reference": ""},  # made by hand at the bank
]


def test_the_references_at_the_bank_rebuild_the_payout_keys():
    assert takeover.payout_key("REQ-SLS-88412 straits-line-88412") == ("invoice:straits-line-88412", "REQ-SLS-88412")
    assert takeover.payout_key("DOA-PAYROLL-2026-11-001") == ("obligation:DOA-PAYROLL-2026-11-001", "DOA-PAYROLL-2026-11-001")
    assert takeover.payout_key("") is None and takeover.payout_key(None) is None


def test_what_the_bank_paid_is_locked_before_anything_else_is_paid(tmp_path):
    store = ExecutionStore(str(tmp_path / "exec.db"))  # a standby's register: it knows nothing of the last payments
    out = asyncio.run(takeover.catch_up_payments(Bank(TRANSFERS), store))
    assert [x["transfer_id"] for x in out["locked"]] == ["tr-1", "tr-2", "tr-4"] and out["not_paid"] == 1
    assert out["unreadable"] == [{"transfer_id": "tr-5", "status": "PAID"}]
    assert store.payout("invoice:straits-line-88412")["status"] == "PAID" and store.payout("invoice:straits-line-88412")["transfer_id"] == "tr-1"
    assert store.payout("invoice:pacific-health-2611")["status"] == "IN_FLIGHT"  # not paid yet, but never paid a second time
    assert store.payout("invoice:clouddesk-2611") is None  # the failed one is free to be paid
    # the executor's own duplicate lock now refuses these invoices
    from venthora.execution.store import DuplicatePayout
    with pytest.raises(DuplicatePayout):
        store.claim_payout("invoice:straits-line-88412", "REQ-SLS-88412", "a-new-execution")
    with pytest.raises(DuplicatePayout):
        store.claim_payout("invoice:pacific-health-2611", "REQ-PHI-2611", "a-new-execution")
    store.claim_payout("invoice:clouddesk-2611", "REQ-CD-2611", "a-new-execution")
    again = asyncio.run(takeover.catch_up_payments(Bank(TRANSFERS), store))  # catching up twice locks nothing twice
    assert again["locked"] == [] and again["already_known"] == 3


def test_the_mailbox_is_read_again_without_making_a_second_request():
    async def fetch(since):
        fetch.since = since
        return [{"message_id": "<a@x>", "raw": b"A"}, {"message_id": "<b@x>", "raw": b"B"}, {"message_id": "<c@x>", "raw": b"bad"}]

    taken = []

    async def ingest(raw):
        if raw == b"bad":
            raise ValueError("no amount found")
        taken.append(raw)

    out = asyncio.run(takeover.reread_mail(fetch, {"<a@x>"}, ingest, now=100_000.0))
    assert fetch.since == 100_000.0 - 24 * 3600  # the last 24 hours
    assert taken == [b"B"] and out["already_in_queue"] == 1 and out["new"] == ["<b@x>"]
    assert out["failed"][0]["message_id"] == "<c@x>"  # one unreadable email never stops the others


def _take_over(tmp_path, lease, org, copied_at):
    async def fetch(since):
        return [{"message_id": "<n@x>", "raw": b"N"}]

    async def ingest(raw):
        return None

    store = ExecutionStore(str(tmp_path / "standby.db"))
    out = asyncio.run(takeover.take_over(lease=lease, org=org, bank=Bank(TRANSFERS), store=store, fetch_since=fetch, known_message_ids=set(),
                                         ingest=ingest, copied_at=copied_at, now=10_000.0))
    return out, store


def test_a_standby_does_nothing_while_the_primary_is_alive(tmp_path, monkeypatch):
    monkeypatch.delenv("VENTHORA_CONTINUITY_URL", raising=False)
    url, clock = str(tmp_path / "lease.db"), Clock(10_000.0)
    WriterLease(url, "app-1", clock=clock).acquire()
    org = Org()
    out, store = _take_over(tmp_path, WriterLease(url, "app-2", clock=clock), org, copied_at=9_000.0)
    assert out["took_over"] is False and "app-1 still holds" in out["reason"]
    assert guard.safe_mode(org)["on"] is False and store.payout("invoice:straits-line-88412") is None  # nothing was changed


def test_a_takeover_locks_the_banks_payments_and_starts_in_safe_mode(tmp_path, monkeypatch):
    monkeypatch.delenv("VENTHORA_CONTINUITY_URL", raising=False)
    monkeypatch.setattr(guard, "_lease", None)
    url, clock = str(tmp_path / "lease.db"), Clock(10_000.0)
    primary = WriterLease(url, "app-1", ttl_s=180, clock=clock)
    primary.acquire()
    clock.t += 600  # the primary died ten minutes ago
    org = Org()
    out, store = _take_over(tmp_path, WriterLease(url, "app-2", clock=clock), org, copied_at=10_000.0 - 2 * 3600)
    assert out["took_over"] is True and out["node"] == "app-2" and out["data_age_minutes"] == 120
    assert store.payout("invoice:straits-line-88412")["status"] == "PAID" and len(out["payments"]["locked"]) == 3
    assert out["mail"]["new"] == ["<n@x>"]
    assert guard.safe_mode(org)["on"] is True and guard.may_pay_automatically(org)[0] is False  # nothing pays by itself
    assert any("120 minutes old" in x for x in out["look_at"]) and any("did not write" in x for x in out["look_at"])
    assert out["look_at"][-1].startswith("compare the book balance")  # a person lifts safe mode, never the standby
    assert not primary.holds()  # and the old primary, if it comes back, is no longer the writer
