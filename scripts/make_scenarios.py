"""Derive the 'receipt delayed' scenario from the baseline by actually reading the inbox.

No hand-written answer: the delayed state is whatever VENTHORA's reader (deterministic lexicon
mode, Verity-verified) concludes from data/inbox/kit01_inbox.json as of its date.

Run: python scripts/make_scenarios.py
"""
import asyncio
import datetime as dt
import json
from pathlib import Path

from venthora.domain.models import TreasuryState
from venthora.evidence.llm import ChatModel
from venthora.evidence.reader import InboxMessage, read_inbox

ROOT = Path(__file__).resolve().parents[1]
DIR = ROOT / "data" / "scenarios"


OUTPUTS = [
    ("kit01_initial", "kit01-initial", "Kit 01 - Initial plan: the inbox as of day 1 (a payee changed bank details)"),
    ("kit01_receipt_delayed", "kit01-receipt-delayed",
     "Kit 01 - New information: the customer email contradicts the receipt forecast"),
]


async def main() -> None:
    base = json.loads((DIR / "kit01_baseline.json").read_text(encoding="utf-8"))
    box = json.loads((ROOT / "data" / "inbox" / "kit01_inbox.json").read_text(encoding="utf-8"))
    messages = [InboxMessage(**m) for m in box["messages"]]
    state = TreasuryState.model_validate(base["state"])
    for (name, case_id, title), day in zip(OUTPUTS, box["timeline"], strict=True):
        reading = await read_inbox(state, messages, as_of=dt.date.fromisoformat(day), model=ChatModel(endpoint="", model=""))
        state = reading.state
        data = state.model_dump() | {"case_id": case_id}
        story = (f"Generated by reading the inbox as of {day}: {reading.stage.summary}. "
                 + " ".join(f"{u.receivable_id}: {u.calibration}." for u in reading.updates)
                 + " ".join(f" {f.obligation_id}: {f.flag.replace('_', ' ')}." for f in reading.flags))
        (DIR / f"{name}.json").write_text(json.dumps({"title": title, "story": story, "state": data}, indent=2) + "\n",
                                          encoding="utf-8")
        print(f"wrote {name}.json: {reading.stage.summary}")


if __name__ == "__main__":
    asyncio.run(main())
